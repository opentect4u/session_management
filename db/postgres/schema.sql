-- =====================================================================================================================
-- AUTH SERVICE - PostgreSQL schema (login, session management, CSRF token, captcha, audit trail, branch scope).
-- Everything lives in the schema "auth". Safe to run more than once (IF NOT EXISTS / ON CONFLICT).
-- Apply with:  npm run db:migrate      (or)      psql -f db/postgres/schema.sql
--
-- Table map
--   auth.roles            role master (SUPERADMIN / ADMIN / EMPLOYEE / OTHER)
--   auth.branches         branches (the "tenant" of a user; also the working scope of a session)
--   auth.users            the people who can log in (username + scrypt password hash + role + home branch)
--   auth.user_branches    which branches a user may work in (extra to the home branch)
--   auth.user_security    per-user lock state, failed-attempt counter, permission version
--   auth.sessions         one row per login session (stores SHA-256 of the cookie value + the CSRF token)
--   auth.login_history    permanent audit trail (never deleted by the cleanup job)
--   auth.captcha_challenges  single-use captcha challenges (answer stored hashed)
-- =====================================================================================================================
CREATE SCHEMA IF NOT EXISTS auth;

-- ---------------------------------------------------------------- role master
CREATE TABLE IF NOT EXISTS auth.roles (
  role_id         smallint    PRIMARY KEY,
  role_code       varchar(20) NOT NULL UNIQUE,   -- stable code used in code/config: SUPERADMIN | ADMIN | EMPLOYEE | OTHER
  role_name       varchar(50) NOT NULL,          -- label shown to people
  hierarchy_level smallint    NOT NULL UNIQUE    -- 1 = most powerful; for "can manage someone of a lower level" checks
);

INSERT INTO auth.roles (role_id, role_code, role_name, hierarchy_level) VALUES
  (1, 'SUPERADMIN', 'Superadmin', 1),
  (2, 'ADMIN',      'Admin',      2),
  (3, 'EMPLOYEE',   'Employee',   3),
  (4, 'OTHER',      'Other',      4)
ON CONFLICT (role_id) DO NOTHING;

-- ---------------------------------------------------------------- branches
CREATE TABLE IF NOT EXISTS auth.branches (
  branch_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- id 0 is reserved to mean "global" (config.scope.globalBranchId)
  branch_name varchar(100) NOT NULL,
  branch_code varchar(10)  NOT NULL UNIQUE,
  sequence    integer      NOT NULL DEFAULT 0,                         -- display order
  CONSTRAINT branches_id_positive_chk CHECK (branch_id > 0)
);

-- ---------------------------------------------------------------- users
CREATE TABLE IF NOT EXISTS auth.users (
  user_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  branch_id     integer      NOT NULL REFERENCES auth.branches (branch_id),   -- home branch = "tenant_id" of the session
  username      varchar(50)  NOT NULL UNIQUE,                                  -- login name
  name          varchar(100) NOT NULL,
  password_hash text         NOT NULL,                                         -- scrypt$N$r$p$salt$hash (never reversible)
  role_id       smallint     NOT NULL REFERENCES auth.roles (role_id),         -- no default: whoever creates a user must choose a role
  is_active     boolean      NOT NULL DEFAULT true,                            -- false = deactivated (sessions die on the next request)
  login_allowed boolean      NOT NULL DEFAULT true,                            -- false = may exist but may not sign in
  created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS users_branch_idx ON auth.users (branch_id);

-- Branches a user is assigned to. A user with NO rows here falls back to their home branch.
CREATE TABLE IF NOT EXISTS auth.user_branches (
  user_branch_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        integer NOT NULL REFERENCES auth.users (user_id) ON DELETE CASCADE,
  branch_id      integer NOT NULL REFERENCES auth.branches (branch_id) ON DELETE CASCADE,
  CONSTRAINT user_branches_unique UNIQUE (user_id, branch_id)
);

-- ---------------------------------------------------------------- per-user security state (row is created on first use)
CREATE TABLE IF NOT EXISTS auth.user_security (
  user_id             integer PRIMARY KEY REFERENCES auth.users (user_id) ON DELETE CASCADE,
  permission_version  integer     NOT NULL DEFAULT 1,   -- bumped when rights change; live sessions adopt it on their next request
  failed_attempts     integer     NOT NULL DEFAULT 0,
  locked_at           timestamptz,                      -- NOT NULL = locked, only an admin can unlock
  last_login_at       timestamptz,
  password_changed_at timestamptz
);

-- ---------------------------------------------------------------- sessions
CREATE TABLE IF NOT EXISTS auth.sessions (
  session_id_hash     char(64)    PRIMARY KEY,          -- SHA-256 of the cookie value; the raw id is never stored
  tenant_id           integer     NOT NULL,             -- = users.branch_id (home branch)
  user_id             integer     NOT NULL REFERENCES auth.users (user_id) ON DELETE CASCADE,
  permission_version  integer     NOT NULL,
  department_scope    jsonb,
  csrf_token          text        NOT NULL,             -- compared with the X-CSRF-Token header on every state-changing request
  ip                  text,
  user_agent          text,
  created_at          timestamptz NOT NULL,
  last_seen_at        timestamptz NOT NULL,
  idle_expires_at     timestamptz NOT NULL,             -- moves forward with activity (inactivity limit)
  absolute_expires_at timestamptz NOT NULL,             -- hard limit, never extended
  revoked_at          timestamptz,
  revoke_reason       text,                             -- LOGOUT | NEW_LOGIN | PASSWORD_CHANGED | USER_DEACTIVATED | ACCOUNT_LOCKED
  scope_mode          text,                             -- NULL = not chosen yet | GLOBAL | BRANCH
  scope_branch_id     integer,
  CONSTRAINT sessions_scope_chk CHECK (
    (scope_mode IS NULL    AND scope_branch_id IS NULL) OR
    (scope_mode = 'GLOBAL' AND scope_branch_id IS NULL) OR
    (scope_mode = 'BRANCH' AND scope_branch_id IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS sessions_user_active_idx ON auth.sessions (user_id) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS sessions_cleanup_idx     ON auth.sessions (absolute_expires_at, idle_expires_at);

-- ---------------------------------------------------------------- audit trail (never cleaned up by the session job)
CREATE TABLE IF NOT EXISTS auth.login_history (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id     integer,                                  -- NULL when the username does not exist; no FK so history survives deletions
  username    text,
  event       text        NOT NULL,                     -- LOGIN_SUCCESS | LOGIN_FAILED | LOGIN_BLOCKED | CAPTCHA_FAILED | ACCOUNT_LOCKED | ...
  reason      text,
  ip          text,
  user_agent  text,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS login_history_user_idx ON auth.login_history (user_id, created_at DESC);

-- ---------------------------------------------------------------- captcha (single use, answer stored hashed)
CREATE TABLE IF NOT EXISTS auth.captcha_challenges (
  id          uuid PRIMARY KEY,
  answer_hash char(64)    NOT NULL,
  expires_at  timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS captcha_expires_idx ON auth.captcha_challenges (expires_at);

